"""
PDF loan assessment report (ReportLab).
"""

from datetime import datetime
from pathlib import Path

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

from config import REPORT_FOLDER
from utils.masking import mask_aadhaar, mask_pan


def _table(rows):
    table = Table(rows, colWidths=[60 * mm, 110 * mm])
    table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#EEF2F7")),
                ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#B8C2CC")),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("FONTSIZE", (0, 0), (-1, -1), 9),
            ]
        )
    )
    return table


def _escape(text) -> str:
    return (
        str(text)
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )


def generate_report(
    application_id,
    customer,
    loan,
    kyc_result,
    fraud_result,
    decision,
) -> str:
    """
    Build the PDF and return its path.

    Identity numbers are masked; the report never contains a full
    PAN or Aadhaar.
    """

    REPORT_FOLDER.mkdir(parents=True, exist_ok=True)

    path = Path(REPORT_FOLDER) / f"loan_report_{application_id}.pdf"

    styles = getSampleStyleSheet()

    story = [
        Paragraph("AI Loan Assessment Report", styles["Title"]),
        Paragraph(
            f"Generated {datetime.now():%d %b %Y %H:%M}",
            styles["Normal"],
        ),
        Spacer(1, 6 * mm),

        Paragraph("Applicant", styles["Heading2"]),
        _table([
            ["Customer ID", customer["customer_id"]],
            ["Name", customer["full_name"]],
            ["PAN", mask_pan(customer["pan"])],
            ["Aadhaar", mask_aadhaar(customer["aadhaar"])],
        ]),
        Spacer(1, 4 * mm),

        Paragraph("Loan Request", styles["Heading2"]),
        _table([
            ["Application ID", application_id],
            ["Loan Type", loan["loan_type"]],
            ["Loan Amount", f"Rs. {loan['loan_amount']:,.0f}"],
            ["Monthly Income", f"Rs. {loan['monthly_income']:,.0f}"],
            ["Tenure", f"{loan['tenure_months'] or '-'} months"],
            ["Credit Score", str(loan["credit_score"])],
        ]),
        Spacer(1, 4 * mm),

        Paragraph("KYC Verification", styles["Heading2"]),
        _table([
            ["Status", kyc_result["verification_status"]],
            ["Name Similarity", f"{kyc_result['similarity_score']}%"],
            ["PAN Match", "Yes" if kyc_result["pan_match"] else "No"],
            ["Aadhaar Match", "Yes" if kyc_result["aadhaar_match"] else "No"],
            ["DOB Match", "Yes" if kyc_result["dob_match"] else "No"],
        ]),
        Spacer(1, 4 * mm),

        Paragraph("Fraud Screening", styles["Heading2"]),
        _table([
            ["Risk Level", fraud_result["risk_level"] if fraud_result else "Not run"],
            ["Score", str(fraud_result["fraud_score"]) if fraud_result else "-"],
            [
                "Findings",
                Paragraph(_escape(fraud_result["reason"]), styles["Normal"])
                if fraud_result else "-",
            ],
        ]),
        Spacer(1, 4 * mm),

        Paragraph("Decision", styles["Heading2"]),
        _table([
            ["Decision", decision["decision"]],
            ["Risk Level", decision["risk_level"]],
        ]),
        Spacer(1, 3 * mm),
    ]

    for paragraph in str(decision["explanation"]).split("\n"):
        if paragraph.strip() and paragraph.strip() != "---":
            story.append(Paragraph(_escape(paragraph), styles["Normal"]))

    story += [
        Spacer(1, 8 * mm),
        Paragraph(
            "This report is generated by an educational AI loan-processing "
            "system and is not a lending commitment.",
            styles["Italic"],
        ),
    ]

    SimpleDocTemplate(
        str(path),
        pagesize=A4,
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        topMargin=16 * mm,
        bottomMargin=16 * mm,
    ).build(story)

    return str(path)
